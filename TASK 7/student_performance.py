df['Average Score']= df[
    ['math score' , 'reading score' , 'writing score']
  ].mean(axis=1)

df['Pass/Fail'] = (
    (
        (df['math score'] >= 40) &
        (df['reading score'] >= 40) &
        (df['writing score'] >= 40)
    ).map({
        True: 'Pass',
        False: 'Fail'
    })
)

Q1=df['math score'].quantile(0.25)
Q3=df['math score'].quantile(0.75)
IQR=Q3-Q1
lower=Q1-1.5*IQR
upper=Q3+1.5*IQR

math_outliers=df[
    (df['math score'] < lower) |
    (df['math score'] > upper)
]

